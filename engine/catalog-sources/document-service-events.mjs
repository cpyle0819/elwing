import {readFile,writeFile} from 'node:fs/promises';
const pages=JSON.parse(await readFile(new URL('./service-events.json',import.meta.url),'utf8'));
const references={},groups=new Map();
for(const page of pages){
 if(page.supersededBy)continue;
 const key=page.page.replace('events-ref-','').replace('.html','');
 const ref=`serviceEvents_${key}`;
 references[ref]={url:page.url,summary:`${page.name}: ${page.directEvents.length?`direct EventBridge events include ${page.directEvents.slice(0,3).join(', ')} (${page.delivery} delivery). `:''}${page.cloudTrail?'The reference also documents API activity delivered through CloudTrail.':''}`.trim()};
 for(const kind of ['direct','cloudTrail']){
  if(kind==='direct'&&!page.directEvents.length||kind==='cloudTrail'&&(!page.cloudTrail||page.id==='aws-cloudtrail'))continue;
  const groupKey=`${page.id}|${kind}`;
  if(!groups.has(groupKey))groups.set(groupKey,{source:page.id,target:kind==='direct'?'eventbridge':'aws-cloudtrail',verb:kind==='direct'?'sends to':'logs to',operation:kind==='direct'?'Service event delivery':'API activity logging',condition:kind==='direct'?'AWS service events, not arbitrary application payloads. Match an EventBridge rule to the documented source and detail-type. Delivery and regional availability depend on the service.':'CloudTrail records supported API activity; this is an audit relationship, not application data delivery. Configure the required trail/event selectors and permissions; data events may require explicit opt-in. EventBridge delivery through CloudTrail requires a separate CloudTrail → EventBridge connection.',references:[],apiReferences:[kind==='direct'?'eventRule':'trailSelectors'],reviewed:page.reviewed});
  const group=groups.get(groupKey);
  group.references.push(ref);
  if(page.scope){
   group.condition+=` ${page.scope}`;
   group.reviewed=page.reviewed;
   for(const [index,evidence] of (page.scopeReferences??[]).entries()){
    const scopeRef=`${ref}_scope${index+1}`;
    references[scopeRef]=evidence;
    group.references.push(scopeRef);
   }
  }
  if(kind==='direct')group.condition+=` Source ${page.eventSource}; examples: ${page.directEvents.slice(0,3).join(', ')}. Delivery: ${page.delivery}.`;

 }
}
await writeFile(new URL('../catalog/service-event-relationships.js',import.meta.url),`// Generated by catalog-sources/document-service-events.mjs from reviewed AWS service event references.\nexport const serviceEventReferences = ${JSON.stringify(references,null,2)};\nexport const serviceEventRelationships = ${JSON.stringify([...groups.values()],null,2)};\n`);
