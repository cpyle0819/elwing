"""Import service icons and their resource types from an official AWS architecture ZIP."""
import json
import pathlib
import re
import sys
import zipfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
FEATURED = {
    'AWS-Lambda': ('lambda', 'Lambda'),
    'Amazon-EC2': ('ec2', 'EC2'),
    'Amazon-API-Gateway': ('apigateway', 'API Gateway'),
    'Amazon-CloudFront': ('cloudfront', 'CloudFront'),
    'Amazon-Route-53': ('route53', 'Route 53'),
    'Amazon-Simple-Storage-Service': ('s3', 'S3'),
    'Amazon-DynamoDB': ('dynamodb', 'DynamoDB'),
    'Amazon-RDS': ('rds', 'RDS'),
    'Amazon-Simple-Queue-Service': ('sqs', 'SQS'),
    'Amazon-EventBridge': ('eventbridge', 'EventBridge'),
    'Amazon-Cognito': ('cognito', 'Cognito'),
    'Amazon-Bedrock': ('bedrock', 'Bedrock'),
}
SHORT_NAMES = {
    'Amazon-Elastic-Kubernetes-Service': 'EKS',
    'Amazon-Elastic-Container-Service': 'ECS',
    'Amazon-Elastic-Container-Registry': 'ECR',
    'Amazon-Virtual-Private-Cloud': 'VPC',
    'AWS-Identity-and-Access-Management': 'IAM',
    'AWS-Key-Management-Service': 'KMS',
    'Amazon-Simple-Notification-Service': 'SNS',
    'Amazon-Simple-Email-Service': 'SES',
    'Amazon-Elastic-Block-Store': 'EBS',
    'Amazon-Managed-Streaming-for-Apache-Kafka': 'MSK',
    'Amazon-Managed-Workflows-for-Apache-Airflow': 'MWAA',
    'AWS-Cloud-Development-Kit': 'CDK',
    'AWS-Command-Line-Interface': 'CLI',
    'AWS-Certificate-Manager': 'ACM',
    'AWS-Database-Migration-Service': 'DMS',
    'AWS-Systems-Manager': 'Systems Manager (SSM)',
    'Elastic-Load-Balancing': 'Elastic Load Balancing (ELB)',
}
CATEGORIES = {'Artificial-Intelligence': 'AI', 'Databases': 'Database',
              'Networking-Content-Delivery': 'Networking', 'Application-Integration': 'Integration',
              'Security-Identity': 'Security'}
archive = zipfile.ZipFile(sys.argv[1])
services = {}
service_ids = {}
for path in sorted(archive.namelist()):
    if not (path.startswith('Architecture-Service-Icons_') and '/48/Arch_' in path and path.endswith('_48.svg')):
        continue
    raw = pathlib.PurePosixPath(path).name[len('Arch_'):-len('_48.svg')]
    category = path.split('/')[1].removeprefix('Arch_')
    category = CATEGORIES.get(category, category.replace('-', ' '))
    full_name = raw.replace('-', ' ').replace('_', ' ')
    name = SHORT_NAMES.get(raw, re.sub(r'^(Amazon|AWS) ', '', full_name))
    service_id = re.sub(r'[^a-z0-9]+', '-', raw.lower()).strip('-')
    if raw in FEATURED:
        service_id, name = FEATURED[raw]
    service_ids[raw] = service_id
    if service_id in services:
        services[service_id]['aliases'] += ' ' + category
        continue
    (ROOT / 'catalog' / 'icons' / f'{service_id}.svg').write_bytes(archive.read(path))
    services[service_id] = dict(id=service_id, name=name, category=category,
                               aliases=full_name, featured=raw in FEATURED)
featured_ids = [item[0] for item in FEATURED.values()]
ordered = sorted(services.values(), key=lambda s: (0, featured_ids.index(s['id'])) if s['featured'] else (1, s['name'].casefold()))
(ROOT / 'catalog' / 'services.json').write_text(json.dumps(ordered, indent=2) + '\n')
print(f'Imported {len(ordered)} unique service icons; {len(featured_ids)} featured.')

# Resource filenames use a few abbreviated parent names; the mapping keeps service IDs stable.
parents = {**service_ids}
for alias, original in {
    'Amazon-VPC': 'Amazon-Virtual-Private-Cloud',
    'Amazon-MSK': 'Amazon-Managed-Streaming-for-Apache-Kafka',
    'Amazon-Elastic-File-System': 'Amazon-EFS',
    'AWS-Datasync': 'AWS-DataSync',
    'AWS-Identity-Access-Management': 'AWS-Identity-and-Access-Management',
    'AWS-IoT': 'AWS-IoT-Core',
}.items():
    if original in service_ids:
        parents[alias] = service_ids[original]
resources, skipped = {}, []
for path in sorted(archive.namelist()):
    if not (path.startswith('Resource-Icons_') and path.endswith('_48.svg')):
        continue
    raw = pathlib.PurePosixPath(path).name[len('Res_'):-len('_48.svg')]
    parent = next((p for p in sorted(parents, key=len, reverse=True)
                   if raw.startswith(p + '_') or raw.startswith(p + '-')), None)
    if not parent:
        skipped.append(raw)
        continue
    resource_id = 'res-' + re.sub(r'[^a-z0-9]+', '-', raw.lower()).strip('-')
    name = raw[len(parent) + 1:].replace('-', ' ').replace('_', ' ')
    (ROOT / 'catalog' / 'icons' / f'{resource_id}.svg').write_bytes(archive.read(path))
    resources[resource_id] = dict(id=resource_id, service=parents[parent], name=name)
types = sorted(resources.values(), key=lambda r: (r['service'], r['name'].casefold(), r['id']))
(ROOT / 'catalog/resource-types-data.js').write_text(
    '// Generated by catalog-sources/import-icons.py from the official AWS icon archive.\n'
    'export const resourceTypes=' + json.dumps(types, indent=2) + ';\n')
print(f'Imported {len(types)} resource types across {len(set(r["service"] for r in types))} services.')
if skipped:
    print('No service parent in this catalog: ' + ', '.join(skipped))
