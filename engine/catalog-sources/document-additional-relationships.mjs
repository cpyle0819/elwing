import {readFile,writeFile} from 'node:fs/promises';
const claims=JSON.parse(await readFile(new URL('./additional-relationships.json',import.meta.url),'utf8'));
const references={},apiReferences={};
const rows=claims.map(({key,reference,apiReference,...row})=>{
 const ref=`additional_${key}`;
 if(references[ref]&&JSON.stringify(references[ref])!==JSON.stringify(reference))throw Error(`Conflicting evidence key: ${key}`);
 if(apiReferences[ref]&&JSON.stringify(apiReferences[ref])!==JSON.stringify(apiReference))throw Error(`Conflicting API key: ${key}`);
 references[ref]=reference;apiReferences[ref]=apiReference;
 return {...row,references:[ref],apiReferences:[ref]};
});
await writeFile(new URL('../catalog/additional-relationships.js',import.meta.url),`// Generated by catalog-sources/document-additional-relationships.mjs from reviewed relationship claims.\nexport const additionalReferences=${JSON.stringify(references,null,2)};\nexport const additionalApiReferences=${JSON.stringify(apiReferences,null,2)};\nexport const additionalRelationships=${JSON.stringify(rows,null,2)};\n`);
